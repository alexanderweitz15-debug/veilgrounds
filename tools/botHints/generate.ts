// Generates src/data/bots/hints/<id>.json (+ registry.ts) for every champion from the champion data:
//   npx tsx tools/botHints/generate.ts            write missing and 'generated' entries, leave 'curated' ones alone
//   npx tsx tools/botHints/generate.ts --check     write nothing; exit 1 if a generated entry is stale or invalid
//   npx tsx tools/botHints/generate.ts --force     also overwrite 'curated' entries (never do this for A27's work)
// The entries come from deriveHints (src/data/bots/hints/derive.ts), so nothing is guessed by hand. A27 curates an
// entry by editing the JSON and setting "status": "curated"; the tool then keeps its hands off.

import { CHAMPION_DATA } from '../../src/sim/champions';
import { deriveHints } from '../../src/data/bots/hints/derive';
import { validateHints } from '../../src/data/bots/hints/validate';

// No @types/node in this repo: load the few Node modules dynamically, as tools/botSim.ts does.
declare const process: { argv: string[]; exit(code: number): never; stdout: { write(s: string): void } };
const fsMod = (await import('node:' + 'fs')) as {
  existsSync(p: string): boolean;
  readFileSync(p: string, enc: string): string;
  writeFileSync(p: string, data: string): void;
};
const pathMod = (await import('node:' + 'path')) as { join(...p: string[]): string };
const urlMod = (await import('node:' + 'url')) as { fileURLToPath(u: URL | string): string };

const dir = pathMod.join(urlMod.fileURLToPath(new URL('../../src/data/bots/hints/', import.meta.url)));
const flags = new Set(process.argv.slice(2));
const check = flags.has('--check');
const force = flags.has('--force');

const ids = Object.keys(CHAMPION_DATA).sort();
let written = 0;
let kept = 0;
let stale = 0;
for (const id of ids) {
  const champ = CHAMPION_DATA[id]!;
  const file = pathMod.join(dir, `${id}.json`);
  const next = JSON.stringify(deriveHints(champ), null, 2) + '\n';
  if (fsMod.existsSync(file)) {
    const cur = fsMod.readFileSync(file, 'utf8');
    const curStatus = (JSON.parse(cur) as { status?: string }).status;
    if (curStatus === 'curated' && !force) {
      kept++;
      const problems = validateHints(JSON.parse(cur), champ);
      if (problems.length) {
        process.stdout.write(problems.join('\n') + '\n');
        stale++;
      }
      continue;
    }
    if (cur === next) continue;
    if (check) {
      process.stdout.write(`stale: ${id}.json differs from the champion data (run tools/botHints/generate.ts)\n`);
      stale++;
      continue;
    }
  } else if (check) {
    process.stdout.write(`missing: ${id}.json\n`);
    stale++;
    continue;
  }
  if (!check) {
    fsMod.writeFileSync(file, next);
    written++;
  }
}

const registry =
  `// GENERATED by tools/botHints/generate.ts - do not edit. Static imports on purpose (import.meta.glob is unavailable\n` +
  `// under tsx / tools/botSim). One line per champion with a hints file.\n\n` +
  ids.map((id) => `import ${id} from './${id}.json';`).join('\n') +
  `\n\nexport const REGISTRY: Readonly<Record<string, unknown>> = {\n${ids.map((id) => `  ${id},`).join('\n')}\n};\n`;
const regFile = pathMod.join(dir, 'registry.ts');
if (check) {
  if (!fsMod.existsSync(regFile) || fsMod.readFileSync(regFile, 'utf8') !== registry) {
    process.stdout.write('stale: registry.ts\n');
    stale++;
  }
} else fsMod.writeFileSync(regFile, registry);

process.stdout.write(`${ids.length} champions: ${written} written, ${kept} curated kept${check ? `, ${stale} problems` : ''}\n`);
if (check && stale) process.exit(1);
